import * as React from 'react';
import { cn } from '../../lib/utils';

export function Card({
  className,
  ...props
}: React.HTMLAttributes<HTMLDivElement>) {
  return (
    <div
      data-slot="card"
      className={cn(
        'rounded-xl border border-[#dde4e2] bg-white text-[#14302b] shadow-2xs',
        className
      )}
      {...props}
    />
  );
}

